import numpy as np

# 1. 创建矩阵 A，形状为 (2, 3)
A = np.array([
    [2, 1, 3],
    [1, 4, 2]
])

# 2. 创建矩阵 B，形状为 (3, 2)
B = np.array([
    [1, 2],
    [3, 1],
    [2, 4]
])

# 3. 输出 A 和 B 的形状
print(np.shape(A))
print(np.shape(B))
# 4. 使用矩阵乘法计算 C
C=A@B
# 5. 输出 C 和 C 的形状
print(C)
print(np.shape(C))
# 6. 尝试交换 A、B 的乘法顺序
print(B@A)
